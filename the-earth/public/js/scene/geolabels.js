const POS = new Map();
const posOf = (n, lat, lon) => { const k = n + lat; if (!POS.has(k)) POS.set(k, llToVec(lat, lon, R * 1.002)); return POS.get(k); };

/** 고도(km)에 맞는 지명 라벨 요청 목록 */
export function geoLabels(alt) {
  const out = [];
  if (alt > 3500 && alt < 90000) for (const [n, lat, lon, k] of BIG) out.push({ key: 'geo' + n + lat, pos: posOf(n, lat, lon), cls: 'geo ' + k, html: n, pri: -1 });
  if (alt > 700 && alt < 9000) for (const [n, lat, lon, k] of MID) out.push({ key: 'geo' + n + lat, pos: posOf(n, lat, lon), cls: 'geo ' + k, html: n, pri: -2 });
  return out;
}
